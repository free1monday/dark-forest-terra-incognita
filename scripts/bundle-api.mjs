/**
 * Bundle Fastify API + shared into a single CJS file for Vercel Node.
 * Prisma client stays external (native engines).
 */
import * as esbuild from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const prismaClient = path.join(root, 'server/node_modules/@prisma/client');

await esbuild.build({
  absWorkingDir: root,
  entryPoints: [path.join(root, 'api/index.ts')],
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
  outfile: path.join(root, 'api/index.js'),
  sourcemap: false,
  external: ['@prisma/client', '.prisma/client'],
  alias: {
    '@shared': path.join(root, 'shared/src/index.ts'),
  },
  resolveExtensions: ['.ts', '.js', '.mjs', '.cjs', '.json'],
  logLevel: 'info',
  plugins: [
    {
      name: 'prisma-from-server',
      setup(build) {
        build.onResolve({ filter: /^@prisma\/client$/ }, () => ({
          path: prismaClient,
          external: true,
        }));
      },
    },
  ],
  banner: {
    js: [
      '/* Dark Forest API — generated by scripts/bundle-api.mjs */',
      // Ensure Node can resolve server-installed Prisma from /api/index.js
      "process.env.NODE_PATH=[require('path').join(__dirname,'../server/node_modules'),process.env.NODE_PATH].filter(Boolean).join(':');",
      "require('module').Module._initPaths();",
    ].join('\n'),
  },
});

console.log('Bundled api/index.js');
